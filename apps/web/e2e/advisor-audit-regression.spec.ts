  await expect(buyerCard).toHaveCount(0);
  await page.getByRole("button", { name: "Müşteri talepleri" }).click();
  await buyerCard.click();
  await page.getByRole("button", { name: "Kriterleri düzenle" }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByRole("checkbox", { name: "Bölge olmazsa olmaz" }).check();
  await expect(dialog.getByRole("spinbutton", { name: "Minimum m²", exact: true })).toHaveValue("180");
  await expect(dialog.getByRole("textbox", { name: "Minimum bütçe TRY", exact: true })).toHaveValue("18000000");
  await dialog.getByRole("textbox", { name: "Bölgeler · virgülle ayır" }).press("Enter");
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Kriterleri kaydet" }).click();
  await expect(dialog).toBeHidden();
  await buyerCard.click();
