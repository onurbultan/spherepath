  await expect(dialog.getByRole("spinbutton", { name: "Asgari bütçe", exact: true })).toHaveValue("18000000");
  await expect(dialog.getByRole("spinbutton", { name: "Azami bütçe", exact: true })).toHaveValue("35000000");
  await expect(dialog.getByRole("spinbutton", { name: "Minimum m²", exact: true })).toHaveValue("180");
  await expect(dialog.getByRole("spinbutton", { name: "Maksimum m²", exact: true })).toHaveValue("");
  await dialog.getByRole("spinbutton", { name: "Azami bütçe", exact: true }).fill("");
  await expect(dialog.getByRole("spinbutton", { name: "Asgari bütçe", exact: true })).toHaveValue("18000000");
  await dialog.getByRole("spinbutton", { name: "Azami bütçe", exact: true }).fill("35000000");
  await dialog.getByRole("combobox", { name: "Not türü", exact: true }).selectOption("requirement");
  await dialog.getByRole("button", { name: "Yeni kişiyi burada oluştur" }).click();
